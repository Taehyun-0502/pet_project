// 캡션을 스캔해 걸리는 주제를 모은다. 대소문자는 무시한다('vlog'/'VLOG')
export function matchTopics(caption) {
  const text = caption.toLowerCase()
  return TOPICS.filter((topic) =>
    TOPIC_KEYWORDS[topic].some((keyword) => text.includes(keyword.toLowerCase()))
  )
}
